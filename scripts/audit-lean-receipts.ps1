# Audits lean/*.lean against the retained GCP receipts.
#
# For each Lean source it computes the canonical SHA-256 of the committed
# (LF) bytes and of the Windows (CRLF) bytes, then searches the evidence
# tree for either value. A source that appears in no receipt is reported as
# UNMATCHED and makes the script exit non-zero.
#
# Usage: powershell -File scripts/audit-lean-receipts.ps1 [-OutFile path]

param(
    [string]$OutFile = ''
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$evidence = Join-Path $root 'evidence'
$leanDir = Join-Path $root 'lean'

function Get-Sha256Hex([byte[]]$bytes) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try { ($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString('x2') }) -join '' }
    finally { $sha.Dispose() }
}

function Get-LfBytes([string]$path) {
    $raw = [System.IO.File]::ReadAllBytes($path)
    $text = [System.Text.Encoding]::UTF8.GetString($raw)
    $lf = $text.Replace("`r`n", "`n")
    return [System.Text.Encoding]::UTF8.GetBytes($lf)
}

# Index text artifacts under evidence/ so a receipt can be found by hash.
# A hash recorded in a receipt README is the primary evidence; a hash that
# only appears in a run log or hash listing is reported separately.
$textFiles = Get-ChildItem -Path $evidence -Recurse -File -Include *.md, *.txt, *.log, *.json, *.sh, *.lean, *.csv
$readmeIndex = @{}
$otherIndex = @{}
foreach ($file in $textFiles) {
    if ($file.Length -gt 4MB) { continue }
    $content = [System.IO.File]::ReadAllText($file.FullName)
    if ($content.Length -eq 0) { continue }
    $rel = $file.FullName.Substring($evidence.Length + 1)
    $receipt = ($rel -split '\\')[0]
    $entry = @{ Text = $content.ToLowerInvariant(); Receipt = $receipt }
    if ($file.Name -eq 'README.md') { $readmeIndex[$file.FullName] = $entry }
    else { $otherIndex[$file.FullName] = $entry }
}

$rows = New-Object System.Collections.Generic.List[object]
foreach ($source in (Get-ChildItem -Path $leanDir -Filter *.lean | Sort-Object Name)) {
    $lfHash = Get-Sha256Hex (Get-LfBytes $source.FullName)
    $crlfHash = Get-Sha256Hex ([System.IO.File]::ReadAllBytes($source.FullName))
    $primary = New-Object System.Collections.Generic.SortedSet[string]
    $secondary = New-Object System.Collections.Generic.SortedSet[string]
    $needles = @($lfHash, $crlfHash) | Select-Object -Unique
    foreach ($entry in $readmeIndex.GetEnumerator()) {
        foreach ($needle in $needles) {
            if ($entry.Value.Text.Contains($needle)) { [void]$primary.Add($entry.Value.Receipt); break }
        }
    }
    foreach ($entry in $otherIndex.GetEnumerator()) {
        foreach ($needle in $needles) {
            if ($entry.Value.Text.Contains($needle)) { [void]$secondary.Add($entry.Value.Receipt); break }
        }
    }
    $receiptText = if ($primary.Count -gt 0) { $primary -join ', ' }
        elseif ($secondary.Count -gt 0) { ($secondary -join ', ') + ' (hash appears only outside a README)' }
        else { '' }
    $rows.Add([pscustomobject]@{
            Source   = $source.Name
            LfHash   = $lfHash
            CrlfHash = $crlfHash
            Receipts = $receiptText
        })
}

$matched = @($rows | Where-Object { $_.Receipts }).Count
$unmatched = @($rows | Where-Object { -not $_.Receipts })

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Lean source receipt audit')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('Generated by `scripts/audit-lean-receipts.ps1`. Do not edit by hand;')
[void]$sb.AppendLine('rerun the script after adding or changing a Lean source or receipt.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('Both the committed LF SHA-256 and the Windows CRLF SHA-256 are')
[void]$sb.AppendLine('reported because older receipts sometimes recorded the CRLF bytes of a')
[void]$sb.AppendLine('working copy rather than the Git blob. A source is matched when either')
[void]$sb.AppendLine('value appears anywhere under `evidence/`.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine(('Sources audited: {0}; matched: {1}; unmatched: {2}.' -f $rows.Count, $matched, $unmatched.Count))
[void]$sb.AppendLine('')
[void]$sb.AppendLine('| Lean source | SHA-256 (LF blob) | Matched receipt(s) |')
[void]$sb.AppendLine('| --- | --- | --- |')
foreach ($row in $rows) {
    $receiptText = if ($row.Receipts) { $row.Receipts } else { '**UNMATCHED**' }
    [void]$sb.AppendLine(('| `{0}` | `{1}` | {2} |' -f $row.Source, $row.LfHash, $receiptText))
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('A hash match establishes only that the receipt records these exact source')
[void]$sb.AppendLine('bytes. The receipt README states what the run certified and what it left')
[void]$sb.AppendLine('open; a match is not a restatement of that scope.')

$report = $sb.ToString()
if ($OutFile) {
    $report | Set-Content -Path $OutFile -Encoding UTF8
    Write-Output "wrote $OutFile"
} else {
    Write-Output $report
}

if ($unmatched.Count -gt 0) {
    Write-Error ("Unmatched Lean sources: " + (($unmatched | ForEach-Object { $_.Source }) -join ', '))
    exit 1
}
exit 0
